// 预解析:半句列表(带所属年级与诗)、上下句配对、朝代作者选项池。
const pairs=[];
const halves=[];
const authors=[];
for(const poem of POEMS){
  authors.push(poem.dynasty+' · '+poem.author);
  for(const line of poem.verse.split('。')){
    if(!line)continue;
    const parts=line.split('，').map(part=>part.trim()).filter(Boolean);
    for(let i=0;i+1<parts.length;i+=2){
      pairs.push({grade:poem.grade,first:parts[i],second:parts[i+1]});
      halves.push({grade:poem.grade,text:parts[i]});
      halves.push({grade:poem.grade,text:parts[i+1]});
    }
  }
}
export const POEM_PAIRS=pairs;
export const POEM_HALVES=halves;
export const POEM_AUTHORS=authors;
