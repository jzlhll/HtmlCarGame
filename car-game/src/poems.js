const blankSpans=new Map(phraseLines.map(line=>{
  const phrases=line.split('/'),spans=[];let start=0;
  for(const phrase of phrases){
    if(phrase.length>=2&&phrase.length<=4)spans.push({start,text:phrase});
    start+=phrase.length;
  }
  return [phrases.join(''),spans];
}));

// 预解析：半句列表保留所属诗篇与年级；课外诗篇不设年级，使用独立题池。
const pairs=[];
const halves=[];
const authors=[];
for(const poem of [...POEMS,...EXTRA_POEMS]){
  authors.push(poem.dynasty+' · '+poem.author);
  for(const line of poem.verse.split('。')){
    if(!line)continue;
    const parts=line.split('，').map(part=>part.trim()).filter(Boolean);
    for(let i=0;i+1<parts.length;i+=2){
      const pair={grade:poem.grade,poem,first:parts[i],second:parts[i+1]};
      pairs.push(pair);
      halves.push({grade:poem.grade,pair,part:0,text:parts[i],blanks:blankSpans.get(parts[i])??[]});
      halves.push({grade:poem.grade,pair,part:1,text:parts[i+1],blanks:blankSpans.get(parts[i+1])??[]});
    }
  }
}
export const POEM_PAIRS=pairs;
export const POEM_HALVES=halves;
export const POEM_AUTHORS=authors;
